#!/usr/bin/env python3
"""M4 wrap-up (P1): reverse-direction scoring on original volumes, forward
3D volume aggregation, CT-side diagnostic table, attribution matrix.

Scoring protocol (registered):
- predictions = each fold's checkpoint_final validation export, regenerated by
  nnU-Net on the ORIGINAL volumes (native geometry, Dataset002 plans; NOT the
  spacing(1,1,1) single-slice exports used by the forward E2 pipeline);
- slice-level Dice scored against labelsTr GT on exactly the 18,322 slices of
  outputs/trusted_us_slices.csv via m3_common.score;
- checkpoint_final only.

Forward 3D volume aggregation (fixed parameters, recorded in RUN_REPORT):
stack the seed's per-slice E2 predictions over the kidney's annotated range,
fill unscored z with empty slices, binary_closing (ball radius 2, 1 iteration),
largest connected component; 3D Dice vs labelsTr GT at 0.3 mm isotropic.

Outputs (all gitignored except the aggregate json):
  outputs/metrics/e4_reverse_slices_{2d,3d}.csv      (per-slice, has case ids)
  outputs/summary/e4_reverse_slice_stats.json        (aggregate, committable)
  outputs/summary/e4_forward_volume3d.json           (aggregate, committable)
  outputs/summary/ct_diagnostic_table.json           (aggregate, committable)
  outputs/summary/attribution_matrix.json            (aggregate, committable)
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import SimpleITK as sitk

sys.path.insert(0, str(Path(__file__).parent))
from m3_common import score  # noqa: E402

ROOT = Path(__import__("os").environ.get("KIDNEYUS_ROOT",
          str(Path(__file__).resolve().parent.parent)))
RES = ROOT / "data/nnunet/nnUNetResults/Dataset002_TRUSTED"
LAB = ROOT / "data/nnunet/nnUNet_raw/Dataset002_TRUSTED/labelsTr"
FWD = ROOT / "outputs/predictions"
CTM = ROOT / "data/raw/TRUSTED/TRUSTED_dataset_for_nsd/CT_DATA/CT_masks/GT_estimated_masksCT"
OFFICIAL = {0: 12, 1: 10, 2: 13, 3: 12, 4: 12}
IOD_DIRECT = 0.906316


def load_slices_csv():
    df = pd.read_csv(ROOT / "outputs/trusted_us_slices.csv")
    out = {}
    for kid, z in zip(df["kidney_id"], df["slice_idx"]):
        out.setdefault(kid, []).append(int(z))
    return out


def part_a_slice_level(slices_by_kidney):
    """Reverse 2d/3d: per-slice Dice of the fold-validation 3D exports on the
    18,322 registered slices."""
    import SimpleITK as sitk
    for cfg in ("2d", "3d_fullres"):
        out_csv = ROOT / f"outputs/metrics/e4_reverse_slices_{cfg}.csv"
        if out_csv.exists():
            print(f"[skip] {cfg} slice csv exists", flush=True)
            continue
        rows = []
        with open(out_csv, "w", newline="") as fh:
            import csv
            w = csv.writer(fh)
            w.writerow(["fold", "kidney_id", "patient", "slice_idx", "dice"])
            for fold in range(5):
                vdir = RES / f"nnUNetTrainer__nnUNetPlans__{cfg}/fold_{fold}/validation"
                preds = sorted(vdir.glob("TRUSTED_*.nii.gz"))
                assert len(preds) == OFFICIAL[fold], (cfg, fold, len(preds))
                for p in preds:
                    kid = p.stem.replace(".nii", "").replace("TRUSTED_", "")
                    img = sitk.ReadImage(str(p))
                    pred = sitk.GetArrayFromImage(img) > 0
                    gt = sitk.GetArrayFromImage(sitk.ReadImage(str(LAB / p.name))) > 0
                    spacing = img.GetSpacing()[::-1]
                    for z in slices_by_kidney[kid]:
                        d, _h = score(pred[z], gt[z], spacing[1:3])  # (y,x) for 2D
                        w.writerow([fold, kid, kid[:3], z, f"{d:.6f}"])
                        rows.append((fold, kid[:3], d))
                print(f"[slice] {cfg} f{fold} done ({len(preds)} volumes)", flush=True)
        df = pd.DataFrame(rows, columns=["fold", "patient", "dice"])
        agg = {"n_slices": int(len(df)),
               "per_fold": {int(f): round(float(v), 4) for f, v in df.groupby("fold")["dice"].mean().items()},
               "overall": round(float(df["dice"].mean()), 4)}
        # patient-level bootstrap CI (39 clusters)
        pv = df.groupby("patient")["dice"].mean()
        rng = np.random.default_rng(42)
        clusters = pv.index.values
        means = np.empty(1000)
        for b in range(1000):
            pick = rng.choice(clusters, len(clusters), replace=True)
            means[b] = pv.loc[pick].mean()
        agg["patient_mean"] = round(float(pv.mean()), 4)
        agg["patient_ci95"] = [round(float(np.percentile(means, 2.5)), 4),
                               round(float(np.percentile(means, 97.5)), 4)]
        key = f"e4_reverse_slice_{cfg}"
        (ROOT / "outputs/summary/e4_reverse_slice_stats.json").exists() and None
        stats_p = ROOT / "outputs/summary/e4_reverse_slice_stats.json"
        stats = json.loads(stats_p.read_text()) if stats_p.exists() else {}
        stats[key] = agg
        stats_p.write_text(json.dumps(stats, indent=1))
        print(f"[slice] {cfg}: {agg}", flush=True)


def stack_and_clean(stack):
    """Fixed parameters: binary_closing (ball r=2, 1 iteration) + largest CC."""
    from scipy import ndimage
    x = ndimage.binary_closing(stack, structure=ndimage.iterate_structure(
        ndimage.generate_binary_structure(3, 1), 2), iterations=1)
    lab, n = ndimage.label(x)
    if n > 1:
        sizes = ndimage.sum(x, lab, range(1, n + 1))
        x = lab == (int(np.argmax(sizes)) + 1)
    return x


def part_b_forward_volume3d(slices_by_kidney):
    import SimpleITK as sitk
    out_p = ROOT / "outputs/summary/e4_forward_volume3d.json"
    done = json.loads(out_p.read_text()) if out_p.exists() else {}
    for seed in (42, 43, 44):
        if str(seed) in done:
            continue
        pred_dir = FWD / f"nnunet_seed{seed}_best/trusted"
        rows = {}
        for kid, zs in slices_by_kidney.items():
            gt_p = LAB / f"TRUSTED_{kid}.nii.gz"
            gt_img = sitk.ReadImage(str(gt_p))
            gt = sitk.GetArrayFromImage(gt_img) > 0
            Z = gt.shape[0]
            stack = np.zeros((Z, gt.shape[1], gt.shape[2]), bool)
            zset = set(zs)
            for z in zset:
                f = pred_dir / f"{kid}_z{z}.nii.gz"
                sl = sitk.GetArrayFromImage(sitk.ReadImage(str(f))) > 0
                stack[z] = np.squeeze(sl)
            cleaned = stack_and_clean(stack)
            inter = np.logical_and(cleaned, gt).sum()
            s = cleaned.sum() + gt.sum()
            d = 2 * inter / s if s else 1.0
            rows[kid] = round(float(d), 6)
        vals = np.array(list(rows.values()))
        done[str(seed)] = {"n": len(rows), "dice3d_mean": round(float(vals.mean()), 4),
                           "dice3d_std": round(float(vals.std()), 4)}
        done[str(seed)]["per_kidney"] = rows
        out_p.write_text(json.dumps(done, indent=1))
        print(f"[fwd3d] seed{seed}: mean={done[str(seed)]['dice3d_mean']}", flush=True)
    seeds = [done[str(s)]["dice3d_mean"] for s in (42, 43, 44)]
    done["three_seed_mean"] = round(float(np.mean(seeds)), 4)
    out_p.write_text(json.dumps(done, indent=1))
    print(f"[fwd3d] 3-seed mean {done['three_seed_mean']}", flush=True)


def part_c_ct_table():
    import SimpleITK as sitk
    out_p = ROOT / "outputs/summary/ct_diagnostic_table.json"
    if out_p.exists():
        print("[skip] ct table exists", flush=True)
        return
    e2 = pd.read_csv(ROOT / "outputs/metrics/e2_external.csv")
    fwd = e2[(e2["model"] == "nnunet") & (e2["prompt"] == "none")]
    fwd_dice = fwd.groupby("kidney_id")["dice"].mean()
    rows = {}
    for p in sorted(CTM.glob("*_maskCT.nii.gz")):
        pid = p.name[:-len(".nii.gz")].replace("_maskCT", "")
        m = sitk.GetArrayFromImage(sitk.ReadImage(str(p)))
        vals = np.unique(m)
        vols = {}
        for lab in vals[vals > 0]:
            vols[str(int(lab))] = int((m == lab).sum())
        rows[pid] = {"ct_kidney_voxels": vols,
                     "ct_total_kidney_voxels": int(sum(vols.values())),
                     "voxel_mm3": 0.3 * 0.3 * 3.0}
    # join US performance by patient prefix
    for pid in rows:
        us_kids = [k for k in fwd_dice.index if k.startswith(pid)]
        if us_kids:
            rows[pid]["us_kidneys"] = us_kids
            rows[pid]["us_fwd_dice"] = round(float(fwd_dice[us_kids].mean()), 4)
    # quartile analysis over kidneys with both
    rec = [(v["ct_total_kidney_voxels"] * v["voxel_mm3"], v.get("us_fwd_dice"))
           for v in rows.values() if v.get("us_fwd_dice") is not None]
    rec = [(v, d) for v, d in rec if not np.isnan(d)]
    qs = np.quantile([v for v, _ in rec], [0.25, 0.5, 0.75])
    quart = []
    for lo, hi in [(0, qs[0]), (qs[0], qs[1]), (qs[1], qs[2]), (qs[2], 1e9)]:
        sel = [d for v, d in rec if lo <= v < hi or (hi > 1e8 and v >= lo)]
        quart.append({"ct_vol_range_mm3": [round(lo, 1), round(min(hi, 1e9), 1)],
                      "n_kidneys": len(sel), "us_fwd_dice_mean": round(float(np.mean(sel)), 4) if sel else None})
    r = np.corrcoef([v for v, _ in rec], [d for _, d in rec])[0, 1]
    out = {"per_patient": rows, "ct_volume_vs_us_dice_pearson_r": round(float(r), 4),
           "ct_volume_quartiles": quart}
    out_p.write_text(json.dumps(out, indent=1))
    print(f"[ct] pearson r = {r:.4f}", flush=True)


def part_d_attribution():
    import SimpleITK as sitk
    out_p = ROOT / "outputs/summary/attribution_matrix.json"
    if out_p.exists():
        return
    sl = json.loads((ROOT / "outputs/summary/e4_reverse_slice_stats.json").read_text())
    fwd3d = json.loads((ROOT / "outputs/summary/e4_forward_volume3d.json").read_text())
    e2agg = json.loads((ROOT / "outputs/summary/aggregate_results.json").read_text())
    pooled = {(e["model"], e["prompt"], e["dataset"]): e["dice_mean"] for e in e2agg["pooled_seeds"]}
    import pandas as pd
    e4 = pd.read_csv(ROOT / "outputs/summary/e4_reverse_cv.csv")
    rev3d = float(e4[e4["config"] == "3d_fullres"]["dice3d"].mean())
    rev2d = float(e4[e4["config"] == "2d"]["dice3d"].mean())
    fwd_head = pooled[("nnunet", "none", "e2")]
    mat = {
        "caliber_note": "slice-mean calibers unless stated; 3D rows are volume Dice "
                        "(reverse = nnU-Net's own 3D exports; forward = stacked E2 "
                        "slices + closing/LCC)",
        "in_domain_ceiling_reverse_cv": {
            "2d_slice": sl["e4_reverse_slice_2d"]["overall"],
            "2d_volume": round(rev2d, 4),
            "3d_volume": round(rev3d, 4)},
        "forward_e2_nnunet_domain_shifted": {
            "2d_slice": fwd_head,
            "3d_volume": fwd3d["three_seed_mean"]},
        "domain_degradation": {
            "2d_slice": round(fwd_head - sl["e4_reverse_slice_2d"]["overall"], 4),
            "3d_volume": round(fwd3d["three_seed_mean"] - rev3d, 4)},
        "annotation_format_ceiling": {
            "iod_direct": IOD_DIRECT,
            "oracle_box_medsam": pooled[("medsam", "p3", "e2")],
            "pole_slice_cost_all_models": "see pole_stratification.json",
        },
    }
    out_p.write_text(json.dumps(mat, indent=1))
    print(json.dumps(mat, indent=1), flush=True)


def main():
    slices_by_kidney = load_slices_csv()
    n = sum(len(v) for v in slices_by_kidney.values())
    assert n == 18322, n
    part_a_slice_level(slices_by_kidney)
    part_b_forward_volume3d(slices_by_kidney)
    part_c_ct_table()
    part_d_attribution()
    print("P1 DONE", flush=True)


if __name__ == "__main__":
    main()
